/**
    Разработать 3 варианта программы с единственным циклом (не считая
 цикла ввода), в которых в соответствии с условием задачи рассматриваются
 строки или столбцы заданной двумерного массива А, имеющего лишь 2-3
 строки (столбца).
    Программа должна предусматривать досрочное завершение цикла
 обработки строк (столбцов) двумерного массива А при выполнении особого,
 оговорённого в задаче, условия. Какие существуют средства досрочного
 выхода из цикла? В чем их преимущества и недостатки? Используйте их в
 разных вариантах своей программы.
    Кроме того, если в процессе обработки строк (столбцов) A удаётся
 проанализировать все его строки (столбцы), то необходимо дополнительно
 предусмотреть вывод текста «Рассмотрен весь двумерный массив».
    Для тестирования программ необходимо разработать 3 теста:
 - условие досрочного выхода не выполняется ни на одном фрагменте двумерного массива;
 - условие досрочного выхода выполняется на последнем её фрагменте;
 - условие досрочного выхода выполняется на любом фрагменте, кроме последнего.

    24. Дан двумерный массив с 2 строками и 10 столбцами. Начиная с первого
 столбца, вычислять и выводить на экран квадраты разности элементов
 каждого столбца, если первый элемент столбца меньше первого элемента
 следующего столбца, а второй элемент – больше второго элемента
 следующего столбца, иначе цикл заканчивать. Последний столбец не
 рассматривать.
*/
#include <stdio.h>
#include <locale.h>
#include <malloc.h>
#include <math.h>

int main()
{
    setlocale(0, "");
    setlocale(LC_NUMERIC, "C");

    printf("\n---------------------------------------------------------------------------------------------------------\n");
//Создание двумерной матрицы
    int n = 2, m;
    do{
        printf("\nВведите количество столбцов m: ");
        scanf("%d", &m);
        if (m < 2 || m >= 100){
            printf("\n=====================================================================\n\t\t");
            printf("Ошибка: нарушен диапазон входных данных");
            printf("\n=====================================================================\n");
        }
    }while (m < 2 || m >= 100);
    printf("\n---------------------------------------------------------------------\n");
    int i, j;
    double* *A;
    A = (double**)malloc(n * sizeof(double*));
    printf("\nВведите элементы массива A:\n");
    for (i = 0; i < n; i++){
        A[i] = (double*)malloc(m * sizeof(double));
        for (j = 0; j < m; j++){
            printf("\nA[%d][%d]: ",i+1,j+1);
            scanf("%lf", &A[i][j]);
        }
    }

    printf("\n---------------------------------------------------------------------------------------------------------\n");
// Вывод введённых данных
    printf("\nВведён массив A:\n");
    printf(" ___");for (i = 0; i < m; i ++) printf(" _________");
    printf("\n|n\\m|"); for (j = 0; j < m; j++) printf(" %4d    |", j+1);
    printf("\n ---");for (i = 0; i < m; i ++) printf("+---------");
    for (i = 0; i < n; i++){
        printf("\n|%2d |", i+1);
        for (j = 0; j < m; j++){
            printf(" %7.2lf |", A[i][j]);
        }
    }
    printf("\n ===");for (i = 0; i < m; i ++) printf(" =========");

    printf("\n\n=========================================================================================================\n");
//Обработка и вывод результата
    printf("\n\t\tРезультат:\n\n");
    int flag = 1;
    double k;
    j = 0;
    while(j < (m-1) && flag){
        if ((A[0][j] < A[0][j+1])&&(A[1][j] > A[1][j+1])){
            k = pow(A[0][j] - A[1][j], 2);
            printf("Столбец %2d: %.2f\n", j+1, k);
            j++;
        }else{
            flag = 0;
        }
    }
    if (flag){
        printf("\nРассмотрен весь двумерный массив\n");
    }else if (j == 0){
        printf("Условие не выполнено для первого столбца. Нет данных для вывода.\n");
    }
    printf("\n=========================================================================================================\n");
//Освобождение памяти
    for (i = 0; i < n; i++){
        free(A[i]);
    }
    free(A);

    return 0;
}
